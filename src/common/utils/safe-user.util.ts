import { AdminUser, Customer } from '@prisma/client';
import { withoutRetiredPermissions } from 'src/permissions/permission-resolution';

export const toSafeAdminUser = (admin: AdminUser) => ({
  id: admin.id,
  name: admin.name,
  displayName: admin.displayName ?? admin.name,
  email: admin.email,
  normalizedEmail: admin.normalizedEmail,
  phone: admin.phone,
  jobTitle: admin.jobTitle,
  notes: admin.notes,
  role: admin.role,
  permissions: withoutRetiredPermissions(admin.permissions),
  deniedPermissions: withoutRetiredPermissions(admin.deniedPermissions),
  isActive: admin.isActive,
  status: admin.status,
  isOwner: admin.isOwner || admin.role === 'OWNER',
  mustChangePassword: admin.mustChangePassword,
  lastLoginAt: admin.lastLoginAt,
  lastSeenAt: admin.lastSeenAt,
  passwordChangedAt: admin.passwordChangedAt,
  deactivatedAt: admin.deactivatedAt,
  createdAt: admin.createdAt,
  updatedAt: admin.updatedAt,
});

export const toSafeCustomer = (customer: Customer) => ({
  id: customer.id,
  displayName: customer.displayName,
  phone: customer.phone,
  whatsappPhone: customer.whatsappPhone,
  tiktokUsername: customer.tiktokUsername,
  status: customer.status,
  verificationStatus: customer.verificationStatus,
  isVirtual: customer.isVirtual,
  purchaseLimitOverride: customer.purchaseLimitOverride,
  totalPurchasedAmount: customer.totalPurchasedAmount,
  totalCancelledAmount: customer.totalCancelledAmount,
  trustLevel: customer.trustLevel,
  notes: customer.notes,
  referralCodeUsed: customer.referralCodeUsed,
  referredByInfluencerId: customer.referredByInfluencerId,
  referralExpiresAt: customer.referralExpiresAt,
  lastLoginAt: customer.lastLoginAt,
  createdAt: customer.createdAt,
  updatedAt: customer.updatedAt,
});
